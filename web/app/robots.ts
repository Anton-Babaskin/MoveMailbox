import type { MetadataRoute } from 'next';
import { SITE } from '@/lib/seo';

/** Экспортируется как статический файл при output: 'export'. */
export const dynamic = 'force-static';

export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: '*',
      allow: '/',
      /**
       * Служебные выгрузки Next рядом с каждой страницей.
       *
       * При статическом экспорте Next кладёт рядом с каждым index.html ещё и
       * текстовую копию страницы для клиентской навигации: index.txt и
       * набор __next.*.txt. На нашем размере это 1220 файлов — больше, чем
       * самих страниц, и каждый отдаёт тот же текст в text/plain (главная —
       * 85 КБ). В карте сайта их нет и ссылками они не стоят, но найти их
       * несложно, а бюджет обхода у молодого домена маленький: потратить его
       * на текстовые дубли вместо страниц — худшее, что с ним можно сделать.
       *
       * Поэтому закрываем ровно их: шаблон с двойным подчёркиванием не задевает
       * /_next/static (скрипты и стили роботу нужны для отрисовки), а llms.txt
       * и robots.txt остаются открытыми — они здесь именно для чтения.
       */
      disallow: ['/*__next', '/*index.txt$'],
    },
    sitemap: `${SITE}/sitemap.xml`,
    /* host здесь был, но это нестандартная директива: Яндекс отказался от
       неё, остальные не читали никогда. Зеркало задаётся редиректом, и он
       у нас есть — www и http уходят на apex по 301. */
  };
}
